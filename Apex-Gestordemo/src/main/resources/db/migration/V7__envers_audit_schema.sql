-- V7: schema explicito das tabelas de historico Envers usadas pelas entidades auditadas.
-- A trilha de revisao faz parte do contrato de persistencia e nao deve ser criada
-- implicitamente por Hibernate em ambientes com ddl-auto=validate.

CREATE TABLE IF NOT EXISTS audit_revision (
  revision_id INT PRIMARY KEY AUTO_INCREMENT,
  revision_timestamp BIGINT NOT NULL,
  actor VARCHAR(120),
  source_ip VARCHAR(64),
  user_agent VARCHAR(255),
  correlation_id VARCHAR(80)
);

CREATE TABLE IF NOT EXISTS financial_calculation_aud (
  id_financial_calculation BIGINT NOT NULL,
  REV INT NOT NULL,
  REVTYPE TINYINT NOT NULL,
  tipo_calculo VARCHAR(60),
  ator_login VARCHAR(120),
  input_hash VARCHAR(128),
  input_snapshot VARCHAR(255),
  resultado_snapshot VARCHAR(255),
  criado_em DATETIME,
  empresa_id BIGINT,
  filial_id BIGINT,
  PRIMARY KEY (id_financial_calculation, REV),
  CONSTRAINT fk_fin_calc_aud_revision FOREIGN KEY (REV) REFERENCES audit_revision(revision_id)
);

CREATE TABLE IF NOT EXISTS financial_digital_document_aud (
  id_financial_digital_document BIGINT NOT NULL,
  REV INT NOT NULL,
  REVTYPE TINYINT NOT NULL,
  tipo_documento VARCHAR(80),
  funcionario_nome VARCHAR(160),
  funcionario_email VARCHAR(160),
  status VARCHAR(40),
  cargo_assinante_obrigatorio VARCHAR(80),
  gerado_por VARCHAR(120),
  gerado_em DATETIME,
  assinado_por VARCHAR(160),
  cargo_assinante VARCHAR(80),
  assinado_em DATETIME,
  enviado_em DATETIME,
  assinatura_digital_hash VARCHAR(128),
  conteudo_hash VARCHAR(128),
  conteudo VARCHAR(255),
  assunto_email VARCHAR(180),
  mensagem_email VARCHAR(255),
  referencia VARCHAR(120),
  ultimo_erro VARCHAR(255),
  empresa_id BIGINT,
  filial_id BIGINT,
  PRIMARY KEY (id_financial_digital_document, REV),
  CONSTRAINT fk_fin_doc_aud_revision FOREIGN KEY (REV) REFERENCES audit_revision(revision_id)
);

CREATE TABLE IF NOT EXISTS financial_document_outbox_aud (
  id_financial_document_outbox BIGINT NOT NULL,
  REV INT NOT NULL,
  REVTYPE TINYINT NOT NULL,
  document_id BIGINT,
  status VARCHAR(40),
  queued_by VARCHAR(120),
  queued_at DATETIME,
  sent_at DATETIME,
  attempts INT,
  last_error VARCHAR(255),
  next_attempt_at DATETIME,
  dead_lettered_at DATETIME,
  empresa_id BIGINT,
  filial_id BIGINT,
  PRIMARY KEY (id_financial_document_outbox, REV),
  CONSTRAINT fk_fin_outbox_aud_revision FOREIGN KEY (REV) REFERENCES audit_revision(revision_id)
);

CREATE TABLE IF NOT EXISTS produtos_aud (
  id_produto BIGINT NOT NULL,
  REV INT NOT NULL,
  REVTYPE TINYINT NOT NULL,
  descricao VARCHAR(60),
  custo DECIMAL(10,2),
  codigo_barras VARCHAR(20),
  codigo_interno VARCHAR(40),
  codigo_original VARCHAR(60),
  marca VARCHAR(45),
  grupo VARCHAR(60),
  subgrupo VARCHAR(60),
  unidade_medida VARCHAR(10),
  embalagem VARCHAR(40),
  data_aquisicao DATETIME,
  quantidade_estoque INT,
  estoque_minimo INT,
  valor_venda DECIMAL(10,2),
  margem DECIMAL(10,2),
  localizacao VARCHAR(80),
  situacao_fiscal VARCHAR(60),
  ncm VARCHAR(12),
  cfop VARCHAR(12),
  icms DECIMAL(7,2),
  ipi DECIMAL(7,2),
  pis DECIMAL(7,2),
  cofins DECIMAL(7,2),
  observacoes VARCHAR(500),
  empresa_id BIGINT,
  filial_id BIGINT,
  status INT,
  version BIGINT,
  fornecedor_id BIGINT,
  categoria_id BIGINT,
  PRIMARY KEY (id_produto, REV),
  CONSTRAINT fk_produto_aud_revision FOREIGN KEY (REV) REFERENCES audit_revision(revision_id)
);

CREATE TABLE IF NOT EXISTS produto_venda_aud (
  produto_id BIGINT NOT NULL,
  venda_id BIGINT NOT NULL,
  REV INT NOT NULL,
  REVTYPE TINYINT NOT NULL,
  quantidade INT,
  preco_unitario DECIMAL(10,2),
  custo_unitario DECIMAL(10,2),
  preco_total DECIMAL(10,2),
  PRIMARY KEY (produto_id, venda_id, REV),
  CONSTRAINT fk_produto_venda_aud_revision FOREIGN KEY (REV) REFERENCES audit_revision(revision_id)
);

CREATE TABLE IF NOT EXISTS venda_aud (
  id_venda BIGINT NOT NULL,
  REV INT NOT NULL,
  REVTYPE TINYINT NOT NULL,
  usuario_id BIGINT,
  cliente_id BIGINT,
  status INT,
  status_operacional VARCHAR(24),
  numero_venda VARCHAR(40),
  valor_total DECIMAL(10,2),
  desconto DECIMAL(10,2),
  observacao VARCHAR(255),
  empresa_id BIGINT,
  filial_id BIGINT,
  caixa_sessao_id BIGINT,
  condicao_pagamento_id BIGINT,
  forma_pagamento_real_id BIGINT,
  valor_recebido DECIMAL(12,2),
  troco DECIMAL(12,2),
  diferenca DECIMAL(12,2),
  enviado_caixa_em DATETIME,
  recebido_caixa_em DATETIME,
  finalizado_em DATETIME,
  motivo_recusa VARCHAR(255),
  motivo_cancelamento VARCHAR(255),
  venda_original_id BIGINT,
  tipo_devolucao VARCHAR(16),
  motivo_devolucao VARCHAR(255),
  estoque_movimentado BOOLEAN,
  version BIGINT,
  idempotency_key VARCHAR(128),
  idempotency_payload_hash VARCHAR(64),
  recebimento_idempotency_key VARCHAR(128),
  recebimento_idempotency_payload_hash VARCHAR(64),
  data_venda DATETIME,
  PRIMARY KEY (id_venda, REV),
  CONSTRAINT fk_venda_aud_revision FOREIGN KEY (REV) REFERENCES audit_revision(revision_id)
);
