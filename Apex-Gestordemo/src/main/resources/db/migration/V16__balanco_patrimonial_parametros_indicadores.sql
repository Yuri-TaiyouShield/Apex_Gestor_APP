-- 1. Posicao do Balanco Patrimonial Gerencial por Competencia
CREATE TABLE IF NOT EXISTS balanco_patrimonial_gerencial (
  id_balanco_patrimonial BIGINT PRIMARY KEY AUTO_INCREMENT,
  empresa_id BIGINT NOT NULL,
  filial_id BIGINT NOT NULL,
  competencia_ano_mes VARCHAR(7) NOT NULL,
  data_referencia DATE NOT NULL,
  disponibilidades_caixa_bancos DECIMAL(15,2) NOT NULL DEFAULT 0,
  contas_receber_operacionais DECIMAL(15,2) NOT NULL DEFAULT 0,
  estoques_operacionais DECIMAL(15,2) NOT NULL DEFAULT 0,
  adiantamentos_operacionais DECIMAL(15,2) NOT NULL DEFAULT 0,
  despesas_antecipadas DECIMAL(15,2) NOT NULL DEFAULT 0,
  outros_ativos_circulantes DECIMAL(15,2) NOT NULL DEFAULT 0,
  realizavel_longo_prazo DECIMAL(15,2) NOT NULL DEFAULT 0,
  investimentos_longo_prazo DECIMAL(15,2) NOT NULL DEFAULT 0,
  imobilizado_bruto DECIMAL(15,2) NOT NULL DEFAULT 0,
  depreciacao_acumulada DECIMAL(15,2) NOT NULL DEFAULT 0,
  intangivel DECIMAL(15,2) NOT NULL DEFAULT 0,
  fornecedores_operacionais_cp DECIMAL(15,2) NOT NULL DEFAULT 0,
  obrigacoes_tributarias_trabalhistas_cp DECIMAL(15,2) NOT NULL DEFAULT 0,
  outras_obrigacoes_operacionais_cp DECIMAL(15,2) NOT NULL DEFAULT 0,
  emprestimos_financiamentos_cp DECIMAL(15,2) NOT NULL DEFAULT 0,
  emprestimos_financiamentos_lp DECIMAL(15,2) NOT NULL DEFAULT 0,
  outras_obrigacoes_lp DECIMAL(15,2) NOT NULL DEFAULT 0,
  capital_social DECIMAL(15,2) NOT NULL DEFAULT 0,
  reservas_capital_lucros DECIMAL(15,2) NOT NULL DEFAULT 0,
  lucros_prejuizos_acumulados DECIMAL(15,2) NOT NULL DEFAULT 0,
  depreciacao_amortizacao_periodo DECIMAL(15,2) NOT NULL DEFAULT 0,
  amortizacao_principal_divida_periodo DECIMAL(15,2) NOT NULL DEFAULT 0,
  sincronizado_operacional BOOLEAN NOT NULL DEFAULT TRUE,
  confirmado_gestor BOOLEAN NOT NULL DEFAULT FALSE,
  observacoes VARCHAR(500),
  atualizado_por VARCHAR(80),
  criado_em DATETIME NOT NULL,
  atualizado_em DATETIME,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uk_balanco_patrimonial_tenant_comp UNIQUE (empresa_id, filial_id, competencia_ano_mes),
  INDEX idx_balanco_patrimonial_tenant_data (empresa_id, filial_id, data_referencia)
);

CREATE TABLE IF NOT EXISTS balanco_patrimonial_gerencial_aud (
  id_balanco_patrimonial BIGINT NOT NULL,
  REV INT NOT NULL,
  REVTYPE TINYINT NOT NULL,
  empresa_id BIGINT,
  filial_id BIGINT,
  competencia_ano_mes VARCHAR(7),
  data_referencia DATE,
  disponibilidades_caixa_bancos DECIMAL(15,2),
  contas_receber_operacionais DECIMAL(15,2),
  estoques_operacionais DECIMAL(15,2),
  adiantamentos_operacionais DECIMAL(15,2),
  despesas_antecipadas DECIMAL(15,2),
  outros_ativos_circulantes DECIMAL(15,2),
  realizavel_longo_prazo DECIMAL(15,2),
  investimentos_longo_prazo DECIMAL(15,2),
  imobilizado_bruto DECIMAL(15,2),
  depreciacao_acumulada DECIMAL(15,2),
  intangivel DECIMAL(15,2),
  fornecedores_operacionais_cp DECIMAL(15,2),
  obrigacoes_tributarias_trabalhistas_cp DECIMAL(15,2),
  outras_obrigacoes_operacionais_cp DECIMAL(15,2),
  emprestimos_financiamentos_cp DECIMAL(15,2),
  emprestimos_financiamentos_lp DECIMAL(15,2),
  outras_obrigacoes_lp DECIMAL(15,2),
  capital_social DECIMAL(15,2),
  reservas_capital_lucros DECIMAL(15,2),
  lucros_prejuizos_acumulados DECIMAL(15,2),
  depreciacao_amortizacao_periodo DECIMAL(15,2),
  amortizacao_principal_divida_periodo DECIMAL(15,2),
  sincronizado_operacional BOOLEAN,
  confirmado_gestor BOOLEAN,
  observacoes VARCHAR(500),
  atualizado_por VARCHAR(80),
  criado_em DATETIME,
  atualizado_em DATETIME,
  version BIGINT,
  PRIMARY KEY (id_balanco_patrimonial, REV),
  CONSTRAINT fk_balanco_patr_aud_revision FOREIGN KEY (REV) REFERENCES audit_revision(revision_id)
);

-- 2. Parametros e Benchmarks Configuraveis por Empresa/Filial
CREATE TABLE IF NOT EXISTS parametro_inteligencia_administrativa (
  id_parametro_inteligencia BIGINT PRIMARY KEY AUTO_INCREMENT,
  empresa_id BIGINT NOT NULL,
  filial_id BIGINT NOT NULL,
  segmento_negocio VARCHAR(60) NOT NULL DEFAULT 'VAREJO_GERAL',
  retorno_minimo_mensal_percentual DECIMAL(7,4) NOT NULL DEFAULT 1.5000,
  capital_investido_referencia DECIMAL(15,2) NOT NULL DEFAULT 0,
  taxa_desconto_anual_percentual DECIMAL(7,4) NOT NULL DEFAULT 12.0000,
  margem_contribuicao_minima_percentual DECIMAL(7,4) NOT NULL DEFAULT 25.0000,
  margem_liquida_minima_percentual DECIMAL(7,4) NOT NULL DEFAULT 8.0000,
  markup_margem_desejada_padrao DECIMAL(7,4) NOT NULL DEFAULT 20.0000,
  aliquota_tributos_venda_padrao DECIMAL(7,4) NOT NULL DEFAULT 8.0000,
  taxa_cartao_media_padrao DECIMAL(7,4) NOT NULL DEFAULT 2.5000,
  comissao_venda_padrao DECIMAL(7,4) NOT NULL DEFAULT 2.0000,
  frete_variavel_venda_padrao DECIMAL(7,4) NOT NULL DEFAULT 0.0000,
  ciclo_financeiro_maximo_dias DECIMAL(10,2) NOT NULL DEFAULT 45.00,
  pme_maximo_dias DECIMAL(10,2) NOT NULL DEFAULT 60.00,
  liquidez_corrente_minima DECIMAL(10,4) NOT NULL DEFAULT 1.2000,
  liquidez_seca_minima DECIMAL(10,4) NOT NULL DEFAULT 0.9000,
  liquidez_imediata_minima DECIMAL(10,4) NOT NULL DEFAULT 0.3000,
  endividamento_geral_maximo_percentual DECIMAL(7,4) NOT NULL DEFAULT 60.0000,
  atualizado_por VARCHAR(80),
  criado_em DATETIME NOT NULL,
  atualizado_em DATETIME,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uk_param_inteligencia_tenant UNIQUE (empresa_id, filial_id)
);

CREATE TABLE IF NOT EXISTS parametro_inteligencia_administrativa_aud (
