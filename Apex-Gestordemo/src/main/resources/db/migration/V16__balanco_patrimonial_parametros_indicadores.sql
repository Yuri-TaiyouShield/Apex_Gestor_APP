  REVTYPE TINYINT NOT NULL,
  empresa_id BIGINT,
  filial_id BIGINT,
  segmento_negocio VARCHAR(60),
  retorno_minimo_mensal_percentual DECIMAL(7,4),
  capital_investido_referencia DECIMAL(15,2),
  taxa_desconto_anual_percentual DECIMAL(7,4),
  margem_contribuicao_minima_percentual DECIMAL(7,4),
  margem_liquida_minima_percentual DECIMAL(7,4),
  markup_margem_desejada_padrao DECIMAL(7,4),
  aliquota_tributos_venda_padrao DECIMAL(7,4),
  taxa_cartao_media_padrao DECIMAL(7,4),
  comissao_venda_padrao DECIMAL(7,4),
  frete_variavel_venda_padrao DECIMAL(7,4),
  ciclo_financeiro_maximo_dias DECIMAL(10,2),
  pme_maximo_dias DECIMAL(10,2),
  liquidez_corrente_minima DECIMAL(10,4),
  liquidez_seca_minima DECIMAL(10,4),
  liquidez_imediata_minima DECIMAL(10,4),
  endividamento_geral_maximo_percentual DECIMAL(7,4),
  atualizado_por VARCHAR(80),
  criado_em DATETIME,
  atualizado_em DATETIME,
  version BIGINT,
  PRIMARY KEY (id_parametro_inteligencia, REV),
